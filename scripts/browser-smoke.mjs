import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { once } from 'node:events';
import { chromium } from 'playwright';

const temporary = mkdtempSync(path.join(tmpdir(), 'antfarm-browser-'));
process.env.ANTFARM_HOME = path.join(temporary, 'colony');
process.env.OPENCLAW_STATE_DIR = path.join(temporary, 'openclaw');
process.env.ANTFARM_WORKSPACE = path.join(temporary, 'fixture');
mkdirSync(process.env.ANTFARM_WORKSPACE);
writeFileSync(path.join(process.env.ANTFARM_WORKSPACE, 'README.md'), '# QA repository\n');
writeFileSync(path.join(process.env.ANTFARM_WORKSPACE, 'example.js'), '// TODO: real survey signal\nexport const value = 1;\n');
const { startDashboard } = await import('../dist/server/dashboard.js');
const server = startDashboard(0);
if (!server.listening) await once(server, 'listening');
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
const errors = [];
const check = (condition, label) => { assert.ok(condition, label); console.log(`PASS ${label}`); };
const context = await browser.newContext({ viewport: { width: 1600, height: 1120 }, deviceScaleFactor: 1 });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
let writes = 0;
page.on('request', request => { if (request.method() === 'POST') writes++; });
const state = async () => (await context.request.get(`${base}/api/state`)).json();
async function until(predicate, label) {
  const deadline = Date.now() + 30_000;
  while (Date.now() < deadline) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 100)); }
  throw new Error(`Timed out: ${label}`);
}
async function loaded() {
  await page.waitForFunction(() => document.querySelector('#colony-canvas').dataset.assets === 'ready');
}
mkdirSync('screenshots', { recursive: true });
try {
  await page.goto(base);
  await loaded();
  await page.locator('#scene-empty').waitFor({ state: 'visible' });
  check((await state()).tasks.length === 0, 'fresh live colony is empty');
  check(!await page.locator('#demo-banner').isVisible(), 'live work never shows a demo banner');
  check(await page.locator('#onboarding-panel').isVisible(), 'first-run setup checklist appears');
  await page.locator('#connections-button').click();
  await page.locator('#antseed-check').click();
  await until(async()=>await page.locator('#antseed-badge').innerText()==='Setup needed','Antseed offline diagnostics');
  check((await page.locator('#antseed-status').innerText()).includes('setup'), 'Antseed setup has actionable offline guidance');
  await page.screenshot({path:'screenshots/colony-connections.png',fullPage:true});
  await page.keyboard.press('Escape');
  await page.locator('#onboarding-dismiss').click();
  await page.reload(); await loaded();
  check(!await page.locator('#onboarding-panel').isVisible(), 'setup dismissal persists');
  await page.locator('[data-open-mission]').first().click();
  await page.locator('#mission-dialog button[value="cancel"]').last().click();
  check(!await page.locator('#mission-dialog').isVisible(), 'empty mission can be cancelled without validation trap');
  await page.locator('#empty-survey').click();
  await page.locator('#mission-brief').fill('Inspect this fixture repository');
  const submitted = page.waitForResponse(response => response.url().endsWith('/api/survey') && response.request().method() === 'POST');
  await page.locator('#launch-button').click();
  check((await submitted).status() === 202, 'real survey accepted');
  await until(async () => (await state()).stats.done === 3, 'survey completion');
  await page.locator('#refresh-button').click();
  await page.locator('#status-filter').selectOption('done');
  await until(async () => await page.locator('[data-task-id]').count() === 3, 'three completed survey steps');
  const completed = await state();
  check(completed.tasks.every(task => task.result), 'all survey steps have persisted output');
  check(completed.tasks.some(task => task.result.includes('unfinished-work-marker')), 'survey reports a real fixture finding');
  await page.locator('[data-task-id]').last().click();
  await page.locator('.timeline-row').first().waitFor();
  check((await page.locator('#inspector-body').innerText()).toLowerCase().includes('result'), 'inspector renders stored result and run timeline');
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'screenshots/colony-live.png', fullPage: true });
  await page.reload();
  await loaded();
  check((await state()).stats.done === 3, 'survey survives reload');
  let releaseTimeline, timelineRequested=false;
  const holdTimeline=new Promise(resolve=>{releaseTimeline=resolve;});
  await page.route('**/api/runs/*',async route=>{
    timelineRequested=true; await holdTimeline;
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({steps:[{id:'stale inspector result',status:'done'}]})});
  });
  await page.locator('#status-filter').selectOption('done');
  await page.locator('[data-task-id]').first().click();
  await until(()=>timelineRequested,'held timeline request');
  await page.keyboard.press('Escape');
  await page.locator('#ants-tab').click();
  await page.locator('.ant-item').first().click();
  const timelineResponse=page.waitForResponse(response=>response.url().includes('/api/runs/'));
  releaseTimeline(); await timelineResponse;
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  check(await page.locator('#inspector-eyebrow').innerText()==='SPECIALIST'&&await page.locator('.timeline-row').count()===0,'late task timeline cannot contaminate another inspector');
  await page.keyboard.press('Escape');
  await page.unroute('**/api/runs/*');
  await page.locator('#missions-tab').click();
  await page.locator('[data-open-mission]').first().click();
  await page.locator('#mission-workflow').selectOption('feature-dev');
  check(await page.locator('#launch-button').isDisabled(), 'unconfigured AI workflow cannot dispatch');
  await page.keyboard.press('Escape');
  await page.locator('[data-mode="demo"]').first().click();
  await page.locator('#demo-banner').waitFor({ state: 'visible' });
  check(!await page.locator('#onboarding-panel').isVisible(), 'demo hides live setup diagnostics');
  const frame=()=>page.locator('#colony-canvas').evaluate(canvas=>canvas.toDataURL());
  const animated=await frame();
  await until(async()=>(await frame())!==animated,'animation advances');
  check(true,'colony animation advances while enabled');
  await page.locator('#pause-button').click();
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const paused=await frame();
  await new Promise(resolve=>setTimeout(resolve,250));
  check(await frame()===paused,'pause freezes the rendered colony');
  await page.locator('#pause-button').click();
  await until(async()=>(await frame())!==paused,'animation resumes');
  const writesBeforeDemo = writes;
  await page.locator('[data-open-mission]').first().click();
  await page.locator('#mission-workflow').selectOption('feature-dev');
  await page.locator('#mission-brief').fill('Demo isolation browser test');
  await page.locator('#launch-button').click();
  await page.locator('#mission-dialog').waitFor({ state: 'hidden' });
  check(writes === writesBeforeDemo && (await state()).tasks.length === 3, 'demo dispatch makes no live write');
  await page.locator('#settings-button').click();
  await page.locator('#theme-setting').selectOption('midnight');
  await page.locator('#motion-setting').check();
  await page.locator('#save-settings').click();
  await page.reload();
  await loaded();
  check(await page.locator('html').getAttribute('data-theme') === 'midnight', 'theme persists through reload');
  await page.locator('#settings-button').click();
  check(await page.locator('#motion-setting').isChecked(), 'reduced-motion preference persists');
  await page.locator('#theme-setting').selectOption('moss');
  await page.locator('#save-settings').click();
  await page.locator('#zoom-in').click();
  check(await page.locator('#zoom-level').innerText() === '110%', 'zoom control updates scene');
  await page.locator('#zoom-reset').click();
  await page.locator('#missions-tab').focus();
  await page.keyboard.press('ArrowRight');
  check(await page.locator('#ants-tab').getAttribute('aria-selected') === 'true', 'activity tabs support arrow keys');
  await page.locator('.ant-item').first().click();
  check(await page.locator('#inspector-eyebrow').innerText() === 'SPECIALIST', 'ant roster opens inspector');
  await page.keyboard.press('Escape');
  // A local fixture exercises model discovery without inference or any wallet.
  await page.route('**/api/providers/antseed',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({configured:true,zeroTokenCaps:true,connected:true,models:[{id:'fixture-code-model',zeroTokenPrice:true,toolUse:true,offers:1}],message:'Fixture catalog. No inference.'})}));
  await page.locator('#connections-button').click();
  await page.locator('#antseed-check').click();
  await page.locator('#antseed-models-panel').waitFor();
  check((await page.locator('#antseed-config-command').innerText()).includes("--model 'fixture-code-model'"),'model choice produces a usable CLI configuration command');
  check(await page.locator('#guide-dialog').evaluate(node=>node.scrollWidth<=node.clientWidth),'desktop connection guide has no horizontal overflow');
  await page.keyboard.press('Escape');
  await page.locator('#missions-tab').click();
  await page.screenshot({ path: 'screenshots/colony-desktop.png', fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'desktop has no horizontal overflow');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#snapshot-button').click();
  const download = await downloadEvent;
  check(download.suggestedFilename().startsWith('antfarm-demo-snapshot-'), 'snapshot export labels demo source');
  await page.locator('[data-view="growth"]').click();
  check(await page.locator('.achievement-card').count() === 7, 'seven data-derived milestones render');
  await page.locator('[data-view="workflows"]').click();
  check(await page.locator('.workflow-card').count() === 4, 'workflow catalog includes local utility and AI teams');
  await page.locator('[data-view="colony"]').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.toast').evaluateAll(nodes=>nodes.forEach(node=>node.remove()));
  await page.screenshot({ path: 'screenshots/colony-mobile.png', fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile has no horizontal overflow');
  await page.locator('[data-open-mission]').first().click();
  check(await page.locator('#mission-brief').isVisible(), 'mobile mission dialog works');
  await page.keyboard.press('Escape');
  await page.locator('#settings-button').click();
  await page.locator('#save-settings').click();
  check(await page.locator('.toast-region').evaluate(node=>node.getBoundingClientRect().bottom<=document.querySelector('.rail').getBoundingClientRect().top),'mobile notifications stay above navigation');
  await page.locator('#connections-button').click();
  check(await page.locator('#guide-dialog').evaluate(node=>node.scrollWidth<=node.clientWidth),'mobile connection guide has no horizontal overflow');
  await page.screenshot({path:'screenshots/colony-connections-mobile.png',fullPage:true});
  await page.keyboard.press('Escape');
  // A late live response must never replace a newly selected demo colony.
  const race = await context.newPage();
  race.on('pageerror', error => errors.push(error.message));
  let release;
  const held = new Promise(resolve => { release = resolve; });
  let intercepted = false;
  await race.route('**/api/state', async route => {
    intercepted = true;
    await held;
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(completed) }).catch(() => {});
  });
  await race.goto(base);
  await until(() => intercepted, 'intercept live poll');
  await race.locator('[data-mode="demo"]').first().click();
  release();
  await until(async () => await race.locator('#mission-count').innerText() === '6', 'demo state after late live response');
  check(await race.locator('#demo-banner').isVisible(), 'late live poll preserves demo state');
  await race.close();
  const denied=await context.newPage();
  denied.on('pageerror',error=>errors.push(error.message));
  await denied.addInitScript(()=>{Storage.prototype.setItem=()=>{throw new DOMException('Storage blocked','SecurityError');};});
  await denied.goto(base+'/?demo=1');
  await denied.locator('#settings-button').click();
  await denied.locator('#theme-setting').selectOption('earth');
  await denied.locator('#save-settings').click();
  check(await denied.locator('html').getAttribute('data-theme')==='earth'&&!await denied.locator('#settings-dialog').isVisible(),'settings still apply when persistent storage is denied');
  await denied.close();
  const offlineContext=await browser.newContext();
  const offline=await offlineContext.newPage();
  await offline.route('**/api/state',route=>route.fulfill({status:503,contentType:'application/json',body:'{"error":"Fixture offline"}'}));
  await offline.goto(base);
  await offline.locator('#connection-banner').waitFor();
  await until(async()=>/unavailable|offline/i.test(await offline.locator('#onboarding-status').innerText()),'offline onboarding guidance');
  check(true,'onboarding reports API failure instead of stale readiness');
  await offlineContext.close();
  check(errors.length === 0, `no browser errors (${errors.join('; ')})`);
  console.log('Browser user flows passed. Screenshots saved in screenshots/.');
} catch (error) {
  await page.screenshot({ path: 'screenshots/failure.png', fullPage: true }).catch(() => {});
  throw error;
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
  rmSync(temporary, { recursive: true, force: true });
}
